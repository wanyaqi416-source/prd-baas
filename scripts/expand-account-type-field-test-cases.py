def numbered(items):
    return "\n".join(f"{index}. {item}" for index, item in enumerate(items, start=1))


def make_case(feature, control, title, precondition, data, steps, expected,
              case_type="字段校验", priority="P1", transition="-", note="-"):
    return {
        "端": "管理端",
        "一级模块": "账户类型配置",
        "二级功能": feature,
        "关联按钮或控件": control,
        "用例标题": title,
        "用例类型": case_type,
        "优先级": priority,
        "前置条件": precondition,
        "测试数据": data,
        "操作步骤": numbered(steps),
        "预期结果": numbered(expected),
        "状态变化": transition,
        "备注": note,
    }


