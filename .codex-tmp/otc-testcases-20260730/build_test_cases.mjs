const casePrefix = (row) => row[0].split("-")[1];
const assignedIds = new Set();
const groupedCases = sheetGroups.map((group) => {
  const rows = cases.filter((row) => group.prefixes.includes(casePrefix(row)));
  for (const row of rows) {
    if (assignedIds.has(row[0])) {
      throw new Error(`Duplicate case assignment: ${row[0]}`);
    }
    assignedIds.add(row[0]);
  }
  return { ...group, rows };
});

if (assignedIds.size !== cases.length) {
  const unassigned = cases.filter((row) => !assignedIds.has(row[0])).map((row) => row[0]);
  throw new Error(`Unassigned cases: ${unassigned.join(", ")}`);
}

